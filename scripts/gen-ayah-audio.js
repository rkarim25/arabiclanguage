#!/usr/bin/env node
/* REAL RECITATION for every ayah in the bank.
   ============================================================================
   His ask, 2026-08-30: "for all sentences include audio and also get real live
   audio wherever possible as well."

   Every sentence already gets a synthesised clip (scripts/gen-audio.py, Edge
   neural voices). That is fine for everyday Arabic and wrong for the Qur'an: his
   goal is to understand the Qur'an AS IT IS RECITED, and a text-to-speech voice
   reading an ayah is not recitation — no tajwīd, no madd, none of the rhythm his
   ear has to learn. Practising against it would train him on the wrong signal.

   So the 592 ayat in the bank are mapped to Mishary Alafasy's recording of that
   exact ayah, on audio.qurancdn.com — the SAME host the site already uses for
   word-by-word Qur'an audio, so no new dependency and no new rights question.

   The map is keyed by normalized Arabic text, matching data/audio-manifest.json,
   so js/app.js can consult it first and fall back to the synthesised clip. That
   fallback matters: the recitation is remote, and the service worker only caches
   same-origin audio, so on the commute with no signal the TTS clip still plays.
   Online he gets Alafasy; offline he gets something rather than silence.

   NOT covered, deliberately: the nine hand-split parts of Ayat al-Kursi. Ayah
   audio is per ayah, so playing it for one part of 2:255 would play the whole
   verse and the split would be pointless. Those keep the synthesised clip.

   Run: node scripts/gen-ayah-audio.js
   ============================================================================ */
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..");
const D = f => JSON.parse(fs.readFileSync(path.join(ROOT, "data", f), "utf8"));

const BASE = "https://audio.qurancdn.com/Alafasy/mp3/";
/* MUST match js/app.js normalizeAr exactly — that is the key speak() looks up.
   A near-match is worse than none: the first version of this file used a wider
   tashkeel range and kept ؟ ، ؛ (which live inside the Arabic block, so the
   non-Arabic filter cannot drop them), and only 274 of 566 ayat resolved. */
const norm = s => String(s).replace(/[ً-ٰـۖ-ۭ]/g, "")
  .replace(/[أإآٱ]/g, "ا").replace(/ى/g, "ي")
  .replace(/[؟،؛]/g, "")
  .replace(/[^؀-ۿ\s]/g, "").replace(/\s+/g, " ").trim();

const bank = D("sentence-bank.json");
const verses = D("verses.json");
// surah id -> number, for the ayat that came from verses.json rather than by ref
const numOf = {};
(verses.surahs || []).forEach(s => { numOf[s.id] = s.n; });

const pad3 = n => String(n).padStart(3, "0");
const map = {};
let skippedParts = 0, skippedNoRef = 0, done = 0;

for (const s of bank.sentences) {
  if (s.track !== "quran") continue;
  if (s.part) { skippedParts++; continue; }        // a split has no recording of its own
  let sura = null, aya = null;
  let m = String(s.ref || "").match(/^(\d+):(\d+)$/);
  if (m) { sura = +m[1]; aya = +m[2]; }
  else if ((m = String(s.id).match(/^q:([a-z-]+):(\d+)/))) {
    sura = numOf[m[1]]; aya = +m[2] + 1;           // verses.json indexes from 0
  }
  if (!sura || !aya) { skippedNoRef++; continue; }
  map[norm(s.ar)] = pad3(sura) + pad3(aya);
  done++;
}

fs.writeFileSync(path.join(ROOT, "data", "ayah-audio.json"), JSON.stringify({
  version: 1,
  note: "GENERATED by scripts/gen-ayah-audio.js. Normalized ayah text -> Alafasy recitation id. js/app.js plays this in preference to the synthesised clip and falls back to it when offline. Do not hand-edit.",
  reciter: "Mishary Rashid Alafasy",
  base: BASE,
  map,
}, null, 1));

console.log(`${done} ayat mapped to real recitation (${skippedParts} split parts and ${skippedNoRef} unreferenced keep the synthesised clip)`);
console.log(`spot check: ${BASE}${Object.values(map)[0]}.mp3`);
